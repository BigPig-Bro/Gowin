// BOOT RST — 上电复位扩展：255→127→0 计数产生复位脉冲，避免RGMII时钟未起时复位锁死
//260822    v1.0.0   初始版本
//260915    v1.1.0   i_rst_n异步触发同步释放；复位脉冲生成后同步释放o_rst_n
module boot_rst (
    input        i_clk,
    input        i_rst_n,    //异步复位输入，低有效
    output logic o_rst_n     //复位输出，低有效
);

/********************************************************************************/
/**************************        内部信号        ********************************/
/********************************************************************************/

logic [7:0] cnt            = 8'd255;   //复位扩展计数器
logic       boot_release_n = 1'b1;     //复位脉冲完成标志，1-释放 0-复位

logic       rst_n_sync1    = 1'b0;     //i_rst_n同步释放第一级
logic       rst_n_sync2    = 1'b0;     //i_rst_n同步释放第二级

/********************************************************************************/
/**************************    复位脉冲生成（原逻辑） ****************************/
/********************************************************************************/

// 255→127→0 计数，产生上电复位脉冲
always_ff @(posedge i_clk) begin
    if (cnt == 8'd0) begin
        boot_release_n <= 1'b1;
    end else begin
        cnt <= cnt - 8'd1;

        if (cnt == 8'd127) begin
            boot_release_n <= 1'b0;
        end
    end
end

/********************************************************************************/
/**************************    i_rst_n异步触发、同步释放 *************************/
/********************************************************************************/

// i_rst_n拉低时同步链立即拉低；i_rst_n拉高时逐拍同步释放
always_ff @(posedge i_clk or negedge i_rst_n) begin
    if (!i_rst_n) begin
        rst_n_sync1 <= 1'b0;
        rst_n_sync2 <= 1'b0;
    end else begin
        rst_n_sync1 <= 1'b1;
        rst_n_sync2 <= rst_n_sync1;
    end
end

/********************************************************************************/
/**************************        o_rst_n 同步输出    **************************/
/********************************************************************************/

// i_rst_n拉低异步复位；拉高后需同步链释放且复位脉冲完成才释放
always_ff @(posedge i_clk or negedge i_rst_n) begin
    if (!i_rst_n) begin
        o_rst_n <= 1'b0;
    end else begin
        o_rst_n <= rst_n_sync2 & boot_release_n;
    end
end

endmodule
